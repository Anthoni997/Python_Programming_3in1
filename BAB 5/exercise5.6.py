#Stages of life

age = 25

if age < 2:
    print(f"At age {age}, this person is a baby.")
elif age < 4:
    print(f"At age {age}, this person is a toddler.")
elif age < 13:
    print(f"At age {age}, this person is a kid.")
elif age < 18:
    print(f"At age {age}, this person is a teenager.")
elif age < 65:
    print(f"At age {age}, this person is an adult.")
else:
    print(f"At age {age}, this person is an elder.")